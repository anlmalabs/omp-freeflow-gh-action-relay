#!/bin/sh
# Generate docker-compose.yml for N relays.
#
# Usage: ./generate-compose.sh [count] [--with-tunnels]
#   count: integer 1..64 (default COUNT env, else 10)
#
# One `relay` app (N listeners on BASE_PORT+1..BASE_PORT+N) that egresses
# DIRECTLY from the host/runner IP — no SOCKS, no WARP client containers.
# Pure (mesh) mode: the relay app is host-published as
# `3101-<3100+N>:3001-<3000+N>` for direct ingress.
# With --with-tunnels: appends tunnel-1..N, each dialing the relay by Docker
# service DNS (`http://relay:<BASE_PORT+N>`).
set -eu

# Load .env when present. Only KEY=VALUE lines with shell-safe key names are
# applied, and values already present in the process environment win — so
# `COUNT=5 ./generate-compose.sh` and setup.sh prompts are never overridden.
# The relevant values are baked into the generated compose file, which is why
# editing .env alone changes nothing until this script runs again.
if [ -f .env ]; then
  cr="$(printf '\r')"
  dq='"' # quote characters, so the case patterns need no escapes
  sq="'"
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    # A value-less line is not a KEY=VALUE assignment — skip it instead of
    # self-assigning KEY=KEY.
    case "$line" in *=*) ;; *) continue ;; esac
    key="${line%%=*}"
    val="${line#*=}"
    # Windows-authored files may carry CRLF: a stray CR in a baked value
    # (URL, comma-list) would silently break matching downstream.
    val="${val%"$cr"}"
    # Shell-identifier keys only; a leading digit would alias positional
    # parameters or die under `set -u` despite the skip contract.
    case "$key" in ''|[!A-Za-z_]*|*[!A-Za-z0-9_]*) continue ;; esac
    case "$val" in
      "$dq"*) val="${val#"$dq"}"; val="${val%%"$dq"*}" ;;
      "$sq"*) val="${val#"$sq"}"; val="${val%%"$sq"*}" ;;
      # Bare values follow compose's env-file behaviour: a whitespace-preceded
      # `#…` starts an inline comment and is stripped. Quoted values run up to
      # the closing quote, with any trailing comment ignored; a ` #` inside the
      # quotes is part of the value.
      *) val="${val%%[[:space:]]#*}" ;;
    esac
    # shellcheck disable=SC2163,SC2086 # key is validated above
    eval "cur=\${$key:-}"
    [ -n "$cur" ] || export "$key=$val"
  done < .env
fi

COUNT="${COUNT:-10}"
WITH_TUNNELS=false
for arg in "$@"; do
  case "$arg" in
    --with-tunnels) WITH_TUNNELS=true ;;
    *) COUNT="$arg" ;;
  esac
done


case "$COUNT" in
  ''|*[!0-9]*)
    echo "error: COUNT must be an integer 1..64, got '$COUNT'" >&2
    exit 1
    ;;
esac
if [ "$COUNT" -lt 1 ] || [ "$COUNT" -gt 64 ]; then
  echo "error: COUNT must be an integer 1..64, got '$COUNT'" >&2
  exit 1
fi
if [ "$WITH_TUNNELS" = true ]; then TUNNEL_FLAG=" --with-tunnels"; else TUNNEL_FLAG=""; fi

BASE_PORT="${BASE_PORT:-3000}"
HOST_LO=$((3100 + 1))
HOST_HI=$((3100 + COUNT))
CONT_LO=$((BASE_PORT + 1))
CONT_HI=$((BASE_PORT + COUNT))

# Host binds default to loopback: the relay router trusts anyone who can reach
# it and all shipped tooling probes 127.0.0.1, so only deliberate exposure
# needs INGRESS_BIND. The relay app itself egresses directly — there are no
# SOCKS proxies left to bind.
ROUTER_BIND="${INGRESS_BIND:-127.0.0.1}"
# IPv6 binds would need Compose's bracketed port syntax ("[::]:port:port"),
# which the templates below do not emit — reject rather than write a file
# Docker cannot parse.
case "$ROUTER_BIND" in
  *:*)
    echo "error: INGRESS_BIND must be IPv4 or 0.0.0.0 (IPv6 binds are not supported); got INGRESS_BIND='$ROUTER_BIND'" >&2
    exit 1
    ;;
esac
if [ "$WITH_TUNNELS" = true ]; then
ROUTER_LINE="relay router not host-published; tunnels dial it by Docker service DNS at http://relay:300N"
else
ROUTER_LINE="relay router (direct ingress) on ${ROUTER_BIND}:${HOST_LO}-${HOST_HI} (override bind: INGRESS_BIND)"
fi

{
cat <<HEADER
# Generated by ./generate-compose.sh — do not hand-edit.
# Regenerate: ./generate-compose.sh ${COUNT}${TUNNEL_FLAG}   (COUNT 1..64, default 10)
# Topology: one relay app, direct egress from the host/runner IP.
# Tunnels reach it by Docker service DNS.
# ${ROUTER_LINE}.
# Relay app env (RELAY_COUNT, BASE_PORT, RELAY_ALLOWED_TARGETS) is baked from
# the generation-time environment / .env — regenerate after editing either.

services:
HEADER

if [ "$WITH_TUNNELS" = true ]; then
cat <<ENTRY
  relay:
    build: .
    container_name: warp-relay-app
    restart: always
    environment:
      - RELAY_COUNT=${COUNT}
      - BASE_PORT=${BASE_PORT:-3000}
      - RELAY_ALLOWED_TARGETS=${RELAY_ALLOWED_TARGETS:-https://opencode.ai,https://api.kilo.ai}

ENTRY
else
cat <<ENTRY
  relay:
    build: .
    container_name: warp-relay-app
    restart: always
    environment:
      - RELAY_COUNT=${COUNT}
      - BASE_PORT=${BASE_PORT:-3000}
      - RELAY_ALLOWED_TARGETS=${RELAY_ALLOWED_TARGETS:-https://opencode.ai,https://api.kilo.ai}
    ports:
      - "${ROUTER_BIND}:${HOST_LO}-${HOST_HI}:${CONT_LO}-${CONT_HI}"

ENTRY
fi

if [ "$WITH_TUNNELS" = true ]; then
# No `depends_on: - relay` on tunnels by design: relay rebuilds must never
# cascade-restart these ephemeral tunnels (each restart mints new edge URLs
# and breaks every configured client line).
i=1
while [ "$i" -le "$COUNT" ]; do
PORT=$((BASE_PORT + i))
cat <<ENTRY
  tunnel-${i}:
    image: cloudflare/cloudflared:latest
    container_name: warp-relay-tunnel-${i}
    restart: always
    command: tunnel --no-autoupdate --url http://relay:${PORT}

ENTRY
i=$((i + 1))
done
fi
} > docker-compose.yml

echo "Generated docker-compose.yml with direct egress and ${COUNT} instances."
