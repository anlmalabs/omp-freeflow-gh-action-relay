#!/bin/sh
# Print each relay's port, live egress IP, and tunnel URL (when tunnels
# exist), then the ready-to-paste client commands.
#
# Mesh direct ingress: host port 310N forwards to the relay app's container
# port 300N. Egress is direct — the relay app itself dials the upstream from
# the host/runner IP, so the egress address is read from the relay's own
# health endpoint (it answers with a cloudflare trace body). The client lines
# use the router's actual host bind, parsed from the generated
# docker-compose.yml (the wizard sets INGRESS_BIND to the VPS Tailscale IP for
# mesh installs; the safe default bind is 127.0.0.1, which is not reachable
# from the tailnet and is reported as such). Quick-Tunnel `/freeflow add` lines
# print ONLY when tunnel containers exist (graceful when absent).
#
# Usage: ./get-status.sh [count]     (default COUNT env, else 10)
# A relay app that is still booting (or a tunnel that has no URL yet) prints
# "(starting...)" / "(not ready)" and never aborts the table (safe under
# `set -e` callers too).
set -u

COUNT="${1:-${COUNT:-10}}"

case "$COUNT" in
  ''|*[!0-9]*)
    echo "error: count must be an integer 1..64, got '$COUNT'" >&2
    exit 1
    ;;
esac
if [ "$COUNT" -lt 1 ] || [ "$COUNT" -gt 64 ]; then
  echo "error: count must be an integer 1..64, got '$COUNT'" >&2
  exit 1
fi

# Host binds as generated by generate-compose.sh. Defaults mirror the
# generator's loopback binds when no compose file exists. ROUTER_BIND drives
# both the egress probe (mesh mode publishes the router on the host) and the
# mesh client lines; when the compose file has no published ports (tunnels
# mode) it parses empty and the probe falls back to reading in-container.
ROUTER_BIND="$(sed -n 's/^ *- "\([^":]*\):3101-.*$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
BASE_PORT="$(sed -n 's/^ *- BASE_PORT=\([0-9][0-9]*\)$/\1/p' docker-compose.yml 2>/dev/null | head -n 1)"
[ -n "$BASE_PORT" ] || BASE_PORT=3000

tunnel_url() {
  docker logs "warp-relay-tunnel-$1" 2>&1 \
    | grep -oE 'https://[a-zA-Z0-9.-]+\.trycloudflare\.com' \
    | tail -n 1 || true
}

egress_ip() {
  # Direct egress: the relay app dials upstreams itself, so the egress address
  # is a property of the relay app and comes back on its OWN health endpoint
  # (the trace body carries `ip=`). $1 = instance number, $2 = BASE_PORT —
  # kept separate so each side can add the index in its own numeral space
  # (host 3100+N, container BASE_PORT+N).
  if [ -n "$ROUTER_BIND" ]; then
    # 1. Mesh/direct mode: the router is host-published as 3100+N -> 3000+N,
    # so probe it straight from the host on the parsed bind.
    ip="$(curl -s -m 5 "http://${ROUTER_BIND}:$((3100 + $1))/" 2>/dev/null | sed -n 's/^ip=//p')"
    if [ -n "$ip" ]; then
      printf '%s' "$ip"
      return
    fi
  fi
  # 2. Tunnels mode (nothing published to the host) — read the same health
  # endpoint from inside the app container. node:22-alpine ships no curl/wget,
  # hence node -e. The container's own BASE_PORT is authoritative, falling back
  # to the compose-parsed value; the sum is kept NUMERIC — a bare
  # `(BASE)+$1` would JS-concatenate to "30001" instead of the container port.
  # $2 is that resolved base, so no env lookup is needed at all.
  docker exec "warp-relay-app" \
    node -e "fetch('http://127.0.0.1:'+($2+$1)).then(r=>r.text()).then(t=>console.log(t))" 2>/dev/null \
    | sed -n 's/^ip=//p' || true
}

mesh_ip() {
  if command -v tailscale >/dev/null 2>&1; then
    tailscale ip -4 2>/dev/null | head -n 1 || true
  fi
}

echo "=== Relay status (1..${COUNT}) ==="
printf "%-10s %-8s %-34s %s\n" "INSTANCE" "PORT" "EGRESS IP" "TUNNEL URL"
echo "--------------------------------------------------------------------------------------------"

i=1
while [ "$i" -le "$COUNT" ]; do
  # Container-side port for this relay (BASE_PORT+N). The host side in mesh
  # mode is 3100+N and is derived inside egress_ip; egress_ip takes the BASE
  # separately so it can add the instance index numerically.
  PORT=$((BASE_PORT + i))

  URL="$(tunnel_url "$i")"
  [ -z "$URL" ] && URL="(none / mesh-VPN direct)"

  IP="$(egress_ip "$i" "$BASE_PORT")"
  [ -z "$IP" ] && IP="(starting...)"

  printf "%-10s %-8s %-34s %s\n" "relay-${i}" ":${PORT}" "$IP" "$URL"
  i=$((i + 1))
done

TS_IP="$(mesh_ip)"
[ -z "$TS_IP" ] && TS_IP="<tailscale-ip>"

FOUND_TUNNELS=0
i=1
while [ "$i" -le "$COUNT" ]; do
  URL="$(tunnel_url "$i")"
  if [ -n "$URL" ]; then
    if [ "$FOUND_TUNNELS" -eq 0 ]; then
      echo ""
      echo "=== TryCloudflare Quick Tunnel commands (public HTTPS) ==="
    fi
    FOUND_TUNNELS=1
    echo "/freeflow add ${URL} relay-${i}"
  fi
  i=$((i + 1))
done

# Bind values were parsed at the top of the script. A wildcard router bind
# (0.0.0.0) is dialable from the tailnet, so print the tailnet address;
# loopback is not reachable from clients and gets a fix-up hint instead.
# (IPv6 binds are rejected by the generator, so ROUTER_BIND is always IPv4.)
if [ "$FOUND_TUNNELS" -eq 0 ]; then
  echo ""
  if [ -z "$ROUTER_BIND" ]; then
    echo "=== Mesh-VPN direct: relay router not host-published ==="
    echo "(generate a mesh-mode file: INGRESS_BIND=<tailscale-ip> ./generate-compose.sh ${COUNT})"
  elif [ "$ROUTER_BIND" = "127.0.0.1" ]; then
    echo "=== Mesh-VPN direct: router bound to 127.0.0.1 (not reachable from the tailnet) ==="
    echo "(re-run: INGRESS_BIND=${TS_IP} ./generate-compose.sh ${COUNT} && docker compose up -d)"
  elif [ "$ROUTER_BIND" = "0.0.0.0" ]; then
    echo "=== Mesh-VPN direct commands (router bound on all interfaces) ==="
    i=1
    while [ "$i" -le "$COUNT" ]; do
      TS_PORT=$((3100 + i))
      echo "/freeflow add http://${TS_IP}:${TS_PORT} relay-${i}"
      i=$((i + 1))
    done
  else
    echo "=== Mesh-VPN direct commands (Tailscale private) ==="
    i=1
    while [ "$i" -le "$COUNT" ]; do
      TS_PORT=$((3100 + i))
      echo "/freeflow add http://${ROUTER_BIND}:${TS_PORT} relay-${i}"
      i=$((i + 1))
    done
  fi
else
  echo ""
  echo "=== Mesh-VPN direct: not published in tunnels mode ==="
  echo "(mesh ingress needs a mesh-mode deployment: ./generate-compose.sh ${COUNT})"
fi
